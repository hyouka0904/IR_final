import json
import zipfile
from pathlib import Path

from scripts.makezip import collect_files, write_zip

CFG = {"paths": {"data": "data/coco", "cache": "cache", "results": "results",
                 "vocab": "data/vocab"},
       "user": {"dir": "data/user"}, "pairs": {"dir": "data/pairs"}}


def _touch(root: Path, rel: str, data: bytes = b"x") -> None:
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_bytes(data)


def _tree(root: Path) -> list[str]:
    tracked = ["README.md", "src/pipeline.py", "configs/default.yaml", "results/summary.csv"]
    for rel in tracked + [
        "data/coco/gallery.json", "data/coco/queries_semantic.json",
        "data/coco/train2017/a.jpg", "data/coco/train2017/stray.jpg",
        "data/coco/val2017/q.jpg", "data/coco/annotations/instances_val2017.json",
        "data/coco/annotations/instances_train2017.json",
        "data/vocab/categories_places365.txt", "data/pairs/synth_1/gallery.jpg",
        "cache/clip/flat/index.faiss", "cache/tags/postings.txt",
        "results/per_query/semantic_fusion.csv", "results/runs/semantic_clip.run",
        "data/user/images/1000000000.jpg", ".venv/pyvenv.cfg", "src/__pycache__/x.pyc",
        "team27_hw1.zip", ".superpowers/sdd/ledger.md", "dist/old.zip",
    ]:
        _touch(root, rel)
    (root / "data/coco/gallery.json").write_text(json.dumps([{"image_id": 1, "file_name": "a.jpg"}]))
    return tracked


def test_collect_full_pack_has_everything_to_run_offline(tmp_path):
    tracked = _tree(tmp_path)
    names = {arc for _, arc in collect_files(tmp_path, CFG, tracked, code_only=False)}
    for rel in tracked + ["data/coco/gallery.json", "data/coco/queries_semantic.json",
                          "data/coco/train2017/a.jpg", "data/coco/val2017/q.jpg",
                          "data/coco/annotations/instances_val2017.json",
                          "data/vocab/categories_places365.txt",
                          "data/pairs/synth_1/gallery.jpg", "cache/clip/flat/index.faiss",
                          "cache/tags/postings.txt", "results/per_query/semantic_fusion.csv"]:
        assert rel in names, rel
    for rel in ["data/coco/train2017/stray.jpg",                 # not in the gallery manifest
                "data/coco/annotations/instances_train2017.json",  # 449 MB, only for 01_download
                "results/runs/semantic_clip.run",                 # regenerated by 05_evaluate
                "data/user/images/1000000000.jpg",               # personal demo photos
                ".venv/pyvenv.cfg", "src/__pycache__/x.pyc", "team27_hw1.zip",
                ".superpowers/sdd/ledger.md", "dist/old.zip"]:
        assert rel not in names, rel


def test_collect_code_only_is_just_the_tracked_files(tmp_path):
    tracked = _tree(tmp_path)
    names = [arc for _, arc in collect_files(tmp_path, CFG, tracked, code_only=True)]
    assert sorted(names) == sorted(tracked)


def test_write_zip_puts_everything_under_one_folder(tmp_path):
    tracked = _tree(tmp_path)
    out = tmp_path / "out" / "p.zip"
    files = collect_files(tmp_path, CFG, tracked, code_only=True)
    write_zip(files, out, top="ir-project")
    with zipfile.ZipFile(out) as z:
        assert sorted(z.namelist()) == sorted(f"ir-project/{t}" for t in tracked)
        assert z.testzip() is None
